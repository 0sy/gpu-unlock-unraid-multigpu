"""Extract pinned firmware and generate the cmpunlocker built-in signature."""

from __future__ import annotations

import argparse
import json
import hashlib
import subprocess
import tarfile
from pathlib import Path


PACKAGE_SHA256 = "e17e7c92eeffa178b0fe1f40eb17a47095f8fc3ce4a77bf115cf5bd5a4df86e9"
PAYLOAD_SHA256 = "00de1fab4e97b88216d0aac2abfbc8ff75f90fa3342ecc3216f9fed656bc1abd"
PACKAGE_VERSION = "610.43.03-1"
MANIFEST = Path(__file__).with_name("artifacts-610.43.03.json")
PAYLOAD_SIZE = 0xF800
FILL_DWORD = 0x000004A7
PATCHED_WORDS = {
    int(item['offset'], 16): int(item['value'], 16)
    for item in json.loads(MANIFEST.read_text())['generated_payload']['overrides']
}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def extract_member(package: Path, name: str) -> bytes:
    if package.name.endswith(".zst"):
        process = subprocess.Popen(["zstd", "-dc", str(package)], stdout=subprocess.PIPE)
        try:
            with tarfile.open(fileobj=process.stdout, mode="r|") as archive:
                result = read_member(archive, name)
            if process.wait() != 0:
                raise ValueError("zstd could not read the pinned package")
            return result
        finally:
            if process.stdout:
                process.stdout.close()
            if process.poll() is None:
                process.kill()
                process.wait()
    with tarfile.open(package, mode="r:*") as archive:
        return read_member(archive, name)


def read_member(archive: tarfile.TarFile, name: str) -> bytes:
    result = None
    for member in archive:
        if member.name != name:
            continue
        if result is not None:
            raise ValueError(f"duplicate package member: {name}")
        if not member.isfile() or member.size > 128 * 1024 * 1024:
            raise ValueError(f"not a regular file in package: {name}")
        stream = archive.extractfile(member)
        if stream is None:
            raise ValueError(f"could not read package member: {name}")
        result = stream.read()
    if result is None:
        raise ValueError(f"missing package member: {name}")
    return result


def build_payload(address: int = 0x00823804, value: int = 0xffffffff) -> bytes:
    word = FILL_DWORD.to_bytes(4, "little")
    payload = bytearray(word * (PAYLOAD_SIZE // len(word)))
    for offset, word_value in PATCHED_WORDS.items():
        payload[offset : offset + 4] = word_value.to_bytes(4, "little")
    payload[0xf754:0xf758] = value.to_bytes(4, "little")
    payload[0xf76c:0xf770] = address.to_bytes(4, "little")
    return bytes(payload)


def payload_header() -> str:
    return ("/* SPDX-License-Identifier: GPL-2.0-only */\n"
            "/* Generated by firmware/generate_v67.py from the pinned cmpunlocker template. */\n"
            + "".join(f"GU_PAYLOAD_WORD(0x{offset:04x}, 0x{value:08x})\n"
                      for offset, value in PATCHED_WORDS.items()
                      if offset not in (0xf754, 0xf76c)))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("package", type=Path, help="pinned nvidia-utils-610.43.03 package")
    parser.add_argument("output", type=Path, help="directory for extracted firmware and payload")
    parser.add_argument("--header", type=Path, help="also reproduce the committed C template header")
    parser.add_argument("--payload", action="store_true", help="also emit the offline cmp-signature.bin reference image")
    args = parser.parse_args()

    package_bytes_hash = hashlib.sha256()
    with args.package.open("rb") as package_file:
        for block in iter(lambda: package_file.read(1024 * 1024), b""):
            package_bytes_hash.update(block)
    if package_bytes_hash.hexdigest() != PACKAGE_SHA256:
        raise SystemExit("package SHA-256 does not match the pinned nvidia-utils artifact")

    pkginfo = extract_member(args.package, ".PKGINFO").decode("utf-8", errors="replace")
    if f"pkgver = {PACKAGE_VERSION}" not in pkginfo.splitlines():
        raise SystemExit("package metadata version does not match 610.43.03-1")

    firmware = {}
    for item in json.loads(MANIFEST.read_text())["source_artifacts"][2]["firmware"]:
        blob = extract_member(args.package, item["path"])
        if len(blob) != item["size"] or sha256(blob) != item["sha256"]:
            raise SystemExit("GSP firmware does not match the pinned artifact")
        firmware[Path(item["path"]).name] = blob

    payload = None
    if args.payload or args.header:
        payload = build_payload()
        if sha256(payload) != PAYLOAD_SHA256:
            raise SystemExit("generated payload differs from its pinned SHA-256")
    manifest = json.loads(MANIFEST.read_text())
    notice = manifest["source_artifacts"][2]["notice"]
    license_text = extract_member(args.package, notice["path"])
    if sha256(license_text) != notice["sha256"]:
        raise SystemExit("NVIDIA license notice differs from pinned package")
    args.output.mkdir(parents=True, exist_ok=True)
    for name, blob in firmware.items():
        (args.output / name).write_bytes(blob)
    if args.payload:
        (args.output / "cmp-signature.bin").write_bytes(payload)
    (args.output / "NVIDIA-LICENSE").write_bytes(license_text)
    if args.header:
        args.header.write_text(payload_header())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
